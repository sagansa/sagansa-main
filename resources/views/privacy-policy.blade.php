            <div class="policy-section" id="penyimpanan-data">
                <h2>5. Penyimpanan, Retensi, dan Penghapusan Data</h2>

                <h3>a. Penyimpanan Data</h3>
                <p>Data yang Anda berikan disimpan di server milik PT Sagansa Engineering Indonesia yang berlokasi di Indonesia. Selain itu, beberapa data disimpan secara lokal di perangkat Anda:</p>
                <ul>
                    <li><strong>Token Autentikasi:</strong> Disimpan dalam penyimpanan terenkripsi (Secure Store / Keychain) di perangkat Anda.</li>
                    <li><strong>Cache Offline:</strong> Data produk, kategori, dan riwayat transaksi dapat disimpan dalam database SQLite lokal untuk mendukung fungsi offline.</li>
                    <li><strong>Preferensi Aplikasi:</strong> Pengaturan dan preferensi pengguna disimpan di penyimpanan lokal perangkat.</li>
                </ul>
                <p>Data yang dikirimkan ke server kami ditransmisikan melalui koneksi terenkripsi (TLS/SSL).</p>

                <h3>b. Retensi Data</h3>
                <p>Kami menyimpan data pribadi Anda selama diperlukan untuk tujuan yang dijelaskan dalam Kebijakan Privasi ini, termasuk:</p>
                <ul>
                    <li>Selama akun Anda aktif dan Anda menggunakan Layanan kami.</li>
                    <li>Sejauh diperlukan untuk memenuhi kewajiban hukum, menyelesaikan sengketa, dan menegakkan perjanjian kami.</li>
                    <li>Data transaksi dan keuangan disimpan sesuai dengan ketentuan perpajakan dan regulasi yang berlaku di Indonesia (minimal 5 tahun).</li>
                </ul>

                <h3>c. Penghapusan Akun dan Data</h3>
                <p>Sesuai dengan kebijakan Google Play, jika aplikasi kami menyediakan fitur pembuatan akun, Anda berhak untuk meminta penghapusan akun dan data terkait.</p>
                <p><strong>Cara menghapus akun:</strong></p>
                <ul>
                    <li><strong>Melalui Aplikasi:</strong> Masuk ke menu Pengaturan &gt; Akun &gt; Hapus Akun di masing-masing aplikasi Sagansa.</li>
                    <li><strong>Melalui Email:</strong> Kirim permintaan penghapusan akun ke <a href="mailto:support@sagansa.id">support@sagansa.id</a> dengan subjek "Permintaan Penghapusan Akun" dan disertai informasi akun yang akan dihapus.</li>
                </ul>
                <p><strong>Yang terjadi setelah penghapusan:</strong></p>
                <ul>
                    <li>Akses ke akun dan seluruh layanan akan dinonaktifkan secara permanen.</li>
                    <li>Data pribadi Anda akan dihapus dari sistem aktif kami dalam waktu maksimal 14 (empat belas) hari kerja sejak permintaan diverifikasi.</li>
                    <li>Data yang wajib disimpan berdasarkan ketentuan hukum yang berlaku (misalnya data transaksi untuk kepentingan perpajakan) akan tetap disimpan sesuai periode retensi yang diwajibkan, setelah itu akan dihapus.</li>
                    <li>Data yang telah masuk dalam cadangan (backup) sistem akan dihapus pada siklus penghapusan cadangan berikutnya.</li>
                </ul>
                <p><strong>Catatan khusus:</strong> Untuk Sagansa App yang digunakan oleh karyawan PT Sagansa Engineering Indonesia, pengelolaan akun diatur melalui kebijakan internal perusahaan. Karyawan dapat menghubungi departemen HR atau tim IT internal untuk proses penghapusan akun.</p>
            </div>

            <div class="policy-section" id="keamanan-data">
                <h2>6. Keamanan Data</h2>
                <p>Kami menerapkan langkah-langkah keamanan teknis dan organisasi yang sesuai untuk melindungi data pribadi Anda, termasuk:</p>
                <ul>
                    <li><strong>Enkripsi:</strong> Data ditransmisikan menggunakan enkripsi TLS/SSL. Password disimpan menggunakan hashing yang aman.</li>
                    <li><strong>Kontrol Akses:</strong> Akses ke data dibatasi hanya untuk karyawan yang membutuhkannya untuk menjalankan tugas mereka.</li>
                    <li><strong>Pemantauan:</strong> Kami memantau sistem secara berkala untuk mendeteksi aktivitas mencurigakan atau pelanggaran keamanan.</li>
                    <li><strong>Backup:</strong> Data dicadangkan secara reguler di infrastruktur yang aman untuk mencegah kehilangan data.</li>
                </ul>
                <p>Meskipun kami berusaha keras melindungi data Anda, tidak ada metode transmisi atau penyimpanan elektronik yang 100% aman. Kami tidak dapat menjamin keamanan absolut.</p>
            </div>

