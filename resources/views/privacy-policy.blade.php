                <ul>
                    <li><strong>Data Akun:</strong> Nama, alamat email, jabatan, dan data kepegawaian internal.</li>
                    <li><strong>Dokumentasi Aset:</strong> Foto aset milik perusahaan yang diunggah melalui aplikasi untuk keperluan inventarisasi.</li>
