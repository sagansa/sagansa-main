                    <li><strong>Data Akun:</strong> Nama, alamat email, dan kredensial autentikasi sistem kepabeanan.</li>
                    <li><strong>Data Dokumen Kepabeanan:</strong> Data PIB (Pemberitahuan Impor Barang), PEB (Pemberitahuan Ekspor Barang), manifes, notul, dan dokumen pendukung lainnya.</li>
                    <li><strong>Data Perusahaan:</strong> NITKU (Nomor Identitas Kepabeanan), identitas perusahaan, dan dokumen legalitas.</li>
                    <li><strong>Data Perangkat:</strong> Informasi perangkat dan sistem operasi.</li>
                </ul>

