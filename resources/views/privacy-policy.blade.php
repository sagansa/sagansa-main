                    <li><strong>Data Pembayaran:</strong> Informasi status pembayaran dari penyedia layanan pembayaran (QRIS, dll).</li>
                    <li><strong>Data Perangkat:</strong> Informasi perangkat, sistem operasi, dan pengidentifikasi perangkat unik.</li>
                </ul>

                <h3>Sagansa Attendance</h3>
                <ul>
                    <li><strong>Data Akun:</strong> Nama, alamat email, nomor telepon, dan data profil saat pendaftaran.</li>
                    <li><strong>Data Absensi:</strong> Riwayat check-in/check-out, lokasi GPS (latitude/longitude), dan foto selfie saat absensi.</li>
                    <li><strong>Data Karyawan:</strong> Nama, posisi, jadwal kerja, dan data penggajian terkait kehadiran.</li>
                    <li><strong>Data Cuti & Izin:</strong> Pengajuan cuti, izin, dan dokumen pendukung.</li>
                    <li><strong>Data Perangkat:</strong> Informasi perangkat, sistem operasi, dan pengidentifikasi perangkat unik.</li>
                </ul>

