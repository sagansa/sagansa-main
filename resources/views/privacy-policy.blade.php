            <div class="policy-intro">
                <p>
                    PT Sagansa Engineering Indonesia ("kami", "kita", atau "Sagansa") berkomitmen untuk melindungi privasi dan keamanan data pribadi Anda. Kebijakan Privasi ini menjelaskan bagaimana kami mengumpulkan, menggunakan, menyimpan, dan melindungi informasi pribadi Anda saat menggunakan layanan kami, termasuk aplikasi Sagansa POS, Sagansa Attendance, dan situs web sagansa.id ("Layanan").
                </p>
                <p>
                    Dengan mengakses atau menggunakan Layanan kami, Anda menyetujui pengumpulan dan penggunaan informasi sesuai dengan Kebijakan Privasi ini.
                </p>
            </div>

            <div class="policy-section" id="informasi-yang-dikumpulkan">
                <h2>1. Informasi yang Kami Kumpulkan</h2>

                <h3>a. Informasi yang Anda Berikan Secara Langsung</h3>
                <ul>
                    <li><strong>Data Identitas:</strong> Nama lengkap, alamat email, nomor telepon, dan nama perusahaan/bisnis yang Anda berikan saat mendaftar akun.</li>
                    <li><strong>Data Bisnis:</strong> Nama toko, alamat toko, data produk/menu, harga, kategori, dan informasi operasional bisnis lainnya yang Anda masukkan ke dalam sistem.</li>
                    <li><strong>Data Transaksi:</strong> Catatan penjualan, metode pembayaran, total transaksi, dan informasi order yang diproses melalui platform kami.</li>
                    <li><strong>Data Karyawan:</strong> Informasi karyawan yang Anda masukkan untuk fitur attendance/absensi, termasuk nama, posisi, dan jadwal kerja.</li>
                    <li><strong>Data Komunikasi:</strong> Pesan, umpan balik, dan korespondensi yang Anda kirimkan kepada tim dukungan kami melalui WhatsApp, email, atau formulir kontak.</li>
                </ul>

                <h3>b. Informasi yang Dikumpulkan Secara Otomatis</h3>
                <ul>
                    <li><strong>Data Perangkat:</strong> Jenis perangkat, sistem operasi, versi browser, dan pengidentifikasi perangkat unik.</li>
                    <li><strong>Data Penggunaan:</strong> Halaman yang dikunjungi, fitur yang digunakan, waktu akses, durasi penggunaan, dan pola interaksi dalam aplikasi.</li>
                    <li><strong>Data Lokasi:</strong> Data lokasi perkiraan berdasarkan alamat IP, hanya jika Anda memberikan izin eksplisit.</li>
                    <li><strong>Log Aktivitas:</strong> Riwayat login, tindakan dalam aplikasi, dan log sistem untuk keperluan keamanan.</li>
                </ul>

                <h3>c. Informasi dari Pihak Ketiga</h3>
                <ul>
                    <li><strong>Channel Online:</strong> Data order dari platform mitra seperti GoFood, ShopeeFood, dan GrabFood yang terintegrasi dengan sistem kami.</li>
                    <li><strong>Pembayaran:</strong> Informasi status pembayaran dari penyedia layanan pembayaran (misalnya QRIS) yang Anda gunakan.</li>
                </ul>
            </div>

            <div class="policy-section" id="penggunaan-informasi">
                <h2>2. Bagaimana Kami Menggunakan Informasi Anda</h2>
                <p>Kami menggunakan informasi yang dikumpulkan untuk tujuan berikut:</p>
                <ul>
                    <li><strong>Menyediakan dan Mengoperasikan Layanan:</strong> Memproses pendaftaran, menjalankan fungsi POS dan attendance, memproses transaksi, dan menampilkan data bisnis Anda.</li>
                    <li><strong>Penagihan dan Pembayaran:</strong> Menghitung tagihan berdasarkan persentase omzet, memproses pembayaran, dan mengirimkan invoice.</li>
                    <li><strong>Peningkatan Layanan:</strong> Menganalisis pola penggunaan untuk meningkatkan fitur, performa, dan pengalaman pengguna.</li>
                    <li><strong>Keamanan:</strong> Mendeteksi, mencegah, dan menangani aktivitas penipuan, penyalahgunaan, atau pelanggaran keamanan.</li>
                    <li><strong>Komunikasi:</strong> Mengirimkan notifikasi penting terkait layanan, pembaruan sistem, informasi teknis, dan (dengan persetujuan Anda) materi pemasaran.</li>
                    <li><strong>Kepatuhan Hukum:</strong> Memenuhi kewajiban hukum, regulasi, dan peraturan yang berlaku di Indonesia.</li>
                    <li><strong>Dukungan Pelanggan:</strong> Menanggapi pertanyaan, keluhan, dan permintaan bantuan dari Anda.</li>
                </ul>
            </div>

            <div class="policy-section" id="pembagian-informasi">
                <h2>3. Pembagian dan Pengungkapan Informasi</h2>
                <p>Kami <strong>tidak menjual</strong> data pribadi Anda kepada pihak ketiga. Kami hanya membagikan informasi dalam keadaan berikut:</p>
                <ul>
                    <li><strong>Penyedia Layanan:</strong> Kami berbagi data dengan penyedia layanan teknologi yang membantu kami mengoperasikan platform (misalnya hosting, layanan pembayaran, dan layanan notifikasi). Penyedia layanan ini terikat kontrak untuk melindungi data Anda.</li>
                    <li><strong>Mitra Integrasi:</strong> Data order yang diperlukan diproses bersama platform mitra (GoFood, ShopeeFood, GrabFood) sesuai dengan integrasi channel online yang Anda aktifkan.</li>
                    <li><strong>Kewajiban Hukum:</strong> Kami dapat mengungkapkan informasi jika diwajibkan oleh hukum, proses hukum, permintaan pemerintah, atau regulasi yang berlaku.</li>
                    <li><strong>Perlindungan Hak:</strong> Untuk melindungi hak, properti, atau keselamatan Sagansa, pengguna kami, atau pihak lain, sesuai dengan hukum yang berlaku.</li>
                    <li><strong>Transaksi Bisnis:</strong> Dalam hal merger, akuisisi, atau penjualan aset, data pengguna dapat menjadi bagian dari transaksi tersebut dengan tetap menjaga kerahasiaan.</li>
                </ul>
            </div>

            <div class="policy-section" id="penyimpanan-data">
                <h2>4. Penyimpanan dan Retensi Data</h2>
                <p>Kami menyimpan data pribadi Anda selama diperlukan untuk tujuan yang dijelaskan dalam Kebijakan Privasi ini, termasuk:</p>
                <ul>
                    <li>Selama akun Anda aktif dan Anda menggunakan Layanan kami.</li>
                    <li>Sejauh diperlukan untuk memenuhi kewajiban hukum, menyelesaikan sengketa, dan menegakkan perjanjian kami.</li>
                    <li>Data transaksi dan keuangan disimpan sesuai dengan ketentuan perpajakan dan regulasi yang berlaku di Indonesia (minimal 5 tahun).</li>
                </ul>
                <p>Jika Anda meminta penghapusan akun, kami akan menghapus data pribadi Anda sesuai prosedur, kecuali data yang wajib disimpan berdasarkan hukum yang berlaku.</p>
            </div>

            <div class="policy-section" id="keamanan-data">
                <h2>5. Keamanan Data</h2>
                <p>Kami menerapkan langkah-langkah keamanan teknis dan organisasi yang sesuai untuk melindungi data pribadi Anda, termasuk:</p>
                <ul>
                    <li><strong>Enkripsi:</strong> Data ditransmisikan menggunakan enkripsi TLS/SSL. Password disimpan menggunakan hashing yang aman.</li>
                    <li><strong>Kontrol Akses:</strong> Akses ke data dibatasi hanya untuk karyawan yang membutuhkannya untuk menjalankan tugas mereka.</li>
                    <li><strong>Pemantauan:</strong> Kami memantau sistem secara berkala untuk mendeteksi aktivitas mencurigakan atau pelanggaran keamanan.</li>
                    <li><strong>Backup:</strong> Data dicadangkan secara reguler di infrastruktur yang aman untuk mencegah kehilangan data.</li>
                </ul>
                <p>Meskipun kami berusaha keras melindungi data Anda, tidak ada metode transmisi atau penyimpanan elektronik yang 100% aman. Kami tidak dapat menjamin keamanan absolut.</p>
            </div>

            <div class="policy-section" id="cookies">
                <h2>6. Cookies dan Teknologi Pelacakan</h2>
                <p>Situs web kami menggunakan cookies dan teknologi serupa untuk:</p>
                <ul>
                    <li><strong>Cookies Esensial:</strong> Diperlukan untuk fungsi dasar situs web, seperti autentikasi dan keamanan sesi.</li>
                    <li><strong>Cookies Analitik:</strong> Membantu kami memahami bagaimana pengunjung berinteraksi dengan situs web, sehingga kami dapat meningkatkan pengalaman pengguna.</li>
                    <li><strong>Cookies Fungsional:</strong> Mengingat preferensi Anda dan memberikan pengalaman yang dipersonalisasi.</li>
                </ul>
                <p>Anda dapat mengatur preferensi cookies melalui pengaturan browser Anda. Menonaktifkan cookies tertentu dapat memengaruhi fungsionalitas situs.</p>
            </div>

            <div class="policy-section" id="hak-pengguna">
                <h2>7. Hak Anda</h2>
                <p>Sesuai dengan peraturan perlindungan data yang berlaku, Anda memiliki hak untuk:</p>
                <ul>
                    <li><strong>Mengakses:</strong> Meminta salinan data pribadi yang kami simpan tentang Anda.</li>
                    <li><strong>Memperbaiki:</strong> Meminta koreksi atas data pribadi yang tidak akurat atau tidak lengkap.</li>
                    <li><strong>Menghapus:</strong> Meminta penghapusan data pribadi Anda, dengan memperhatikan kewajiban hukum yang berlaku.</li>
                    <li><strong>Membatasi:</strong> Meminta pembatasan pemrosesan data pribadi Anda dalam kondisi tertentu.</li>
                    <li><strong>Menarik Persetujuan:</strong> Menarik persetujuan yang telah Anda berikan sebelumnya untuk pemrosesan data tertentu.</li>
                    <li><strong>Portabilitas:</strong> Meminta transfer data pribadi Anda dalam format yang terstruktur dan dapat dibaca mesin.</li>
                </ul>
                <p>Untuk menggunakan hak-hak tersebut, silakan hubungi kami melalui informasi kontak di bawah. Kami akan merespons permintaan Anda dalam waktu yang wajar dan sesuai dengan ketentuan hukum yang berlaku.</p>
            </div>

            <div class="policy-section" id="data-anak">
                <h2>8. Privasi Anak</h2>
                <p>Layanan kami tidak ditujukan untuk anak-anak di bawah usia 18 tahun. Kami tidak secara sengaja mengumpulkan data pribadi dari anak-anak. Jika Anda mengetahui bahwa anak Anda telah memberikan data pribadi kepada kami, silakan hubungi kami dan kami akan mengambil langkah untuk menghapus informasi tersebut.</p>
            </div>

            <div class="policy-section" id="perubahan-kebijakan">
                <h2>9. Perubahan Kebijakan Privasi</h2>
                <p>Kami dapat memperbarui Kebijakan Privasi ini dari waktu ke waktu untuk mencerminkan perubahan dalam praktik kami atau persyaratan hukum. Perubahan akan berlaku efektif segera setelah dipublikasikan di halaman ini dengan tanggal "Terakhir diperbarui" yang baru.</p>
                <p>Untuk perubahan material, kami akan memberikan pemberitahuan yang lebih menonjol, seperti pemberitahuan melalui aplikasi atau email, sebelum perubahan berlaku efektif.</p>
                <p>Kami mendorong Anda untuk meninjau Kebijakan Privasi ini secara berkala.</p>
            </div>

