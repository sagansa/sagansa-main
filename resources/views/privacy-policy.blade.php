                <p>
                    PT Sagansa Engineering Indonesia ("kami", "kita", atau "Sagansa") berkomitmen untuk melindungi privasi dan keamanan data pribadi Anda. Kebijakan Privasi ini menjelaskan bagaimana kami mengumpulkan, menggunakan, menyimpan, dan melindungi informasi pribadi Anda saat menggunakan layanan kami, termasuk aplikasi Sagansa POS, Sagansa Attendance, Sagansa CEISA, Sagansa App, dan situs web sagansa.id ("Layanan").
